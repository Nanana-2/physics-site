def problems(subject):
    for ci, (chapter, items) in enumerate(subject[3], 1):
        for pi, item in enumerate(items, 1):
            title, level, note = item.split("|", 2)
            yield ci, chapter, pi, title, int(level), note


def batches():
    """分野ごとに，章の切れ目で，できるだけ同じ大きさ（BATCH_LIMIT 以下）に分ける。"""
    import math
    out = []
    for subj in SUBJECTS:
        sizes = [len(items) for _, items in subj[3]]
        k = math.ceil(sum(sizes) / BATCH_LIMIT)
        target = sum(sizes) / k
        cur, count, made = [], 0, 0
        for ci, n in enumerate(sizes, 1):
            if cur and made < k - 1 and count + n / 2 > target:
                out.append((subj, cur)); cur, count, made = [], 0, made + 1
            cur.append(ci); count += n
        out.append((subj, cur))
    return out


