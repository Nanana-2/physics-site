"""AIっぽい硬い言い回しを，普通の言い方に置き換える（数式の外だけ）。Web 版と PDF 原稿の両方に当てる。
使い方: python3 plain_words.py [-n]"""
import re, sys, glob
REP = [
    # 適用する → 用いる
    (r'を適用すると', 'を用いると'), (r'を適用します', 'を用います'), (r'を適用して', 'を用いて'),
    (r'を適用し，', 'を用い，'), (r'を適用した', 'を用いた'), (r'を適用する', 'を用いる'),
    (r'を適用すれば', 'を用いれば'), (r'を適用できます', 'を用いることができます'), (r'を適用でき', 'を用いることができ'),
    (r'を適用され', 'を用いられ'), (r'を適用し', 'を用い'), (r'を適用', 'を用いること'),
    # 意味する → 表す
    (r'を意味します', 'を表します'), (r'を意味する', 'を表す'), (r'を意味し，', 'を表し，'), (r'を意味して', 'を表して'),
    (r'を意味し', 'を表し'),
    # 等置
    (r'等置します', '等しいとおきます'), (r'等置すると', '等しいとおくと'), (r'等置して', '等しいとおいて'),
    (r'等置し，', '等しいとおき，'), (r'等置した', '等しいとおいた'), (r'等置する', '等しいとおく'), (r'等置により', '等しいとおくことにより'),
    (r'等置', '等しいとおくこと'),
    # 消失
    (r'消失します', '消えます'), (r'消失する', '消える'), (r'消失して', '消えて'), (r'消失し', '消え'),
    # 相殺
    (r'相殺します', '打ち消し合います'), (r'相殺されます', '打ち消し合います'), (r'相殺され', '打ち消され'),
    (r'相殺して', '打ち消し合って'), (r'相殺し', '打ち消し合い'), (r'相殺する', '打ち消し合う'),
    # 帰着
    (r'に帰着されることを', 'になることを'), (r'に帰着することを', 'になることを'), (r'に帰着されます', 'になります'),
    (r'に帰着します', 'になります'), (r'に帰着され，', 'になり，'), (r'に帰着され', 'になり'), (r'に帰着する', 'になる'),
    (r'へと帰着する', 'になる'), (r'に帰着させ', 'の形に直し'),
    # 非零
    (r'非零実定数倍', '0 でない実数倍'), (r'非零の', '0 でない'), (r'非零', '0 でない'),
]
def plain(s):
    for a, b in REP: s = s.replace(a, b)
    return s
dry = '-n' in sys.argv
files = glob.glob('docs/*/*/*.md') + glob.glob('private/pdf-books/source/*-full*/problems/*.tex')
changed = 0
for f in files:
    t = open(f).read()
    parts = re.split(r'(\$\$.*?\$\$|\$[^$\n]*\$|\\\[.*?\\\]|\\begin\{(?:align|equation|gather)\*?\}.*?\\end\{(?:align|equation|gather)\*?\})', t, flags=re.S)
    u = ''.join(p if i % 2 else plain(p) for i, p in enumerate(parts))
    if u != t:
        changed += 1
        if not dry: open(f, 'w').write(u)
print('files changed', changed)
